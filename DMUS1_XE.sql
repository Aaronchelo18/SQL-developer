INSERT INTO DIM_TIEMPO (
  FECHA_COMPLETA,
  ANIO,
  MES,
  NOMBRE_MES,
  SEMANA_EPIDEMIOLOGICA
)
SELECT
  FECHA_ATENCION                                   AS FECHA_COMPLETA,
  EXTRACT(YEAR  FROM FECHA_ATENCION)              AS ANIO,
  EXTRACT(MONTH FROM FECHA_ATENCION)              AS MES,
  INITCAP(
    TO_CHAR(
      FECHA_ATENCION,
      'MONTH',
      'NLS_DATE_LANGUAGE=SPANISH'
    )
  )                                               AS NOMBRE_MES,
  TO_NUMBER(TO_CHAR(FECHA_ATENCION, 'WW'))        AS SEMANA_EPIDEMIOLOGICA
FROM STG_ATENCION
WHERE FECHA_ATENCION IS NOT NULL
GROUP BY FECHA_ATENCION;


