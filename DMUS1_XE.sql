INSERT INTO HECHOS_ATENCIONES (
  ID_TIEMPO,
  ID_PACIENTE,
  ID_PROFESIONAL,
  ID_DIAGNOSTICO,
  ID_UBICACION,
  CONTADOR_ATENCIONES,
  DURACION_ATENCION_MINUTOS
)
SELECT
  dt.ID_TIEMPO,
  dp.ID_PACIENTE,
  dpr.ID_PROFESIONAL,
  dd.ID_DIAGNOSTICO,
  du.ID_UBICACION,
  1 AS CONTADOR_ATENCIONES,
  sa.DURACION_MINUTOS
FROM STG_ATENCION sa
JOIN DIM_TIEMPO dt
  ON dt.FECHA_COMPLETA = sa.FECHA_ATENCION
JOIN DIM_PACIENTE dp
  ON dp.DNI_PACIENTE = sa.DNI_PACIENTE
JOIN DIM_PROFESIONAL dpr
  ON dpr.DNI_PROFESIONAL = sa.DNI_PROFESIONAL
JOIN DIM_DIAGNOSTICO dd
  ON dd.CODIGO_CIE10 = sa.CODIGO_CIE10
JOIN DIM_UBICACION du
  ON du.CODIGO_TOPICO         = sa.CODIGO_TOPICO
 AND du.CODIGO_CENTRO_ATENCION = sa.CODIGO_CENTRO_ATENCION
WHERE sa.FECHA_ATENCION       IS NOT NULL
  AND sa.DNI_PACIENTE         IS NOT NULL
  AND sa.DNI_PROFESIONAL      IS NOT NULL
  AND sa.CODIGO_CIE10         IS NOT NULL;


