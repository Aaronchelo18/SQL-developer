-- DIMENSIONES DEL MODELO ESTRELLA
---------------------------------------------------------

-- 1) Dimensión TIEMPO
CREATE TABLE DIM_TIEMPO (
  ID_TIEMPO              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FECHA_COMPLETA         DATE       NOT NULL,
  ANIO                   NUMBER(4)  NOT NULL,
  MES                    NUMBER(2)  NOT NULL,
  NOMBRE_MES             VARCHAR2(20),
  SEMANA_EPIDEMIOLOGICA  NUMBER(2)
);

CREATE INDEX IX_DIM_TIEMPO_FECHA ON DIM_TIEMPO(FECHA_COMPLETA);

-- 2) Dimensión PACIENTE
CREATE TABLE DIM_PACIENTE (
  ID_PACIENTE   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  DNI_PACIENTE  CHAR(8),
  NOMBRE_COMPLETO VARCHAR2(150),
  SEXO          VARCHAR2(10),
  UBIGEO        VARCHAR2(6)
);

-- 3) Dimensión PROFESIONAL
CREATE TABLE DIM_PROFESIONAL (
  ID_PROFESIONAL   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  DNI_PROFESIONAL  CHAR(8),
  SERVICIO         VARCHAR2(100),
  CONDICION_LABORAL VARCHAR2(50)
);

-- 4) Dimensión DIAGNOSTICO
CREATE TABLE DIM_DIAGNOSTICO (
  ID_DIAGNOSTICO   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO_CIE10     VARCHAR2(10),
  RESULTADO_FINAL  VARCHAR2(100),
  CODIGO_EMERGENCIA VARCHAR2(20)
);

-- 5) Dimensión UBICACION
CREATE TABLE DIM_UBICACION (
  ID_UBICACION          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO_TOPICO         VARCHAR2(20),
  CODIGO_CENTRO_ATENCION VARCHAR2(50)
);

---------------------------------------------------------
-- TABLA DE HECHOS
---------------------------------------------------------
CREATE TABLE HECHOS_ATENCIONES (
  PK_HECHO                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_TIEMPO                  NUMBER NOT NULL,
  ID_PACIENTE                NUMBER NOT NULL,
  ID_PROFESIONAL             NUMBER NOT NULL,
  ID_DIAGNOSTICO             NUMBER NOT NULL,
  ID_UBICACION               NUMBER NOT NULL,
  CONTADOR_ATENCIONES        NUMBER DEFAULT 1,
  DURACION_ATENCION_MINUTOS  NUMBER,

  CONSTRAINT FK_HECHO_TIEMPO
    FOREIGN KEY (ID_TIEMPO)     REFERENCES DIM_TIEMPO(ID_TIEMPO),
  CONSTRAINT FK_HECHO_PACIENTE
    FOREIGN KEY (ID_PACIENTE)   REFERENCES DIM_PACIENTE(ID_PACIENTE),
  CONSTRAINT FK_HECHO_PROFESIONAL
    FOREIGN KEY (ID_PROFESIONAL) REFERENCES DIM_PROFESIONAL(ID_PROFESIONAL),
  CONSTRAINT FK_HECHO_DIAGNOSTICO
    FOREIGN KEY (ID_DIAGNOSTICO) REFERENCES DIM_DIAGNOSTICO(ID_DIAGNOSTICO),
  CONSTRAINT FK_HECHO_UBICACION
    FOREIGN KEY (ID_UBICACION)   REFERENCES DIM_UBICACION(ID_UBICACION)
);




