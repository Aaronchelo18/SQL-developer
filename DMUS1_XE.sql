CREATE OR REPLACE VIEW VW_CUBO_ATENCIONES AS
SELECT
  h.PK_HECHO,
  -- Tiempo
  t.FECHA_COMPLETA,
  t.ANIO,
  t.MES,
  t.NOMBRE_MES,
  t.SEMANA_EPIDEMIOLOGICA,
  -- Paciente
  p.DNI_PACIENTE,
  p.SEXO,
  p.UBIGEO,
  -- Profesional
  pr.DNI_PROFESIONAL,
  pr.SERVICIO,
  pr.CONDICION_LABORAL,
  -- Diagnóstico
  d.CODIGO_CIE10,
  d.RESULTADO_FINAL,
  d.CODIGO_EMERGENCIA,
  -- Ubicación
  u.CODIGO_TOPICO,
  u.CODIGO_CENTRO_ATENCION,
  -- Medidas
  h.CONTADOR_ATENCIONES,
  h.DURACION_ATENCION_MINUTOS
FROM HECHOS_ATENCIONES h
JOIN DIM_TIEMPO      t  ON t.ID_TIEMPO      = h.ID_TIEMPO
JOIN DIM_PACIENTE    p  ON p.ID_PACIENTE    = h.ID_PACIENTE
JOIN DIM_PROFESIONAL pr ON pr.ID_PROFESIONAL = h.ID_PROFESIONAL
JOIN DIM_DIAGNOSTICO d  ON d.ID_DIAGNOSTICO = h.ID_DIAGNOSTICO
JOIN DIM_UBICACION   u  ON u.ID_UBICACION   = h.ID_UBICACION;


